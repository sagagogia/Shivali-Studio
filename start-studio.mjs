import {spawn} from 'node:child_process';
import {takeServerLock} from './server-lock.mjs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {recoverInterruptedJobs,getSnapshot} from '../src/studio/core.ts';
import {dataDir} from '../src/studio/store.ts';
import {authMode} from '../src/studio/auth.ts';
const mode=process.argv.includes('--dev')?'dev':'start';
const req=createRequire(createRequire(import.meta.url).resolve('next/package.json'));
req('@next/env').loadEnvConfig(process.cwd(),mode==='dev',{info(){},error(){}});
const hostname=process.env.SHIVALI_HOST||'127.0.0.1';
if(!['127.0.0.1','localhost','0.0.0.0'].includes(hostname))throw new Error('Unsupported studio bind address');
if((hostname==='0.0.0.0'||process.env.RENDER==='true')&&authMode('https://studio.invalid')!=='protected')throw new Error('Hosted binding requires a password of at least 16 characters and session secret of at least 32 characters');
const lock=path.join(dataDir(),'server.pid');
const cleanup=takeServerLock(lock);
process.on('exit',cleanup);
const count=recoverInterruptedJobs();getSnapshot();
if(count)console.log(`Recovered ${count} interrupted jobs as failed; provider reservations retained.`);
const child=spawn(process.execPath,[path.resolve('node_modules/next/dist/bin/next'),mode,'--hostname',hostname,'--port',process.env.PORT||'3001'],{stdio:'inherit',env:{...process.env,NEXT_TELEMETRY_DISABLED:'1'}});
for(const sig of ['SIGINT','SIGTERM'])process.on(sig,()=>child.kill(sig));
child.on('exit',code=>{process.exitCode=code??1;});
